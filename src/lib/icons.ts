// Fail the build early if an icon is not a clean 16×16 grid.
for (const [name, rows] of Object.entries(icons)) {
  if (rows.length !== 16 || rows.some((r) => r.length !== 16 || /[^.#+]/.test(r))) {
    throw new Error(`Icon "${name}" must be 16 rows of 16 characters using . # +`);
  }
}

export type IconName = keyof typeof icons;
export const iconNames = Object.keys(icons) as [IconName, ...IconName[]];

/** Converts an icon grid to two SVG paths (main and secondary colour). */
export function iconPaths(name: IconName): { main: string; second: string } {
  let main = '';
  let second = '';
  icons[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === ch) x++;
      const run = `M${start} ${y}h${x - start}v1h-${x - start}z`;
      if (ch === '#') main += run;
      else second += run;
    }
  });
  return { main, second };
}
